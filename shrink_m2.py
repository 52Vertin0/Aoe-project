"""M2（manageMilitary 注释压缩）：纯注释操作，代码零改。
   安全断言：被替换区间内每一行必须是注释行或空行，否则 ABORT（绝不误删代码）。
   保留：结论 / 关键理由 / 用户需求日期；删除：考古过程、重复表述、已失效分支说明。
"""
P = 'UsrAI.cpp'
s = open(P, encoding='utf-8', newline='').read()
assert '\r\n' in s, 'CRLF 缺失'
s = s.replace('\r\n', '\n')
lines = s.split('\n')
total = [0]


def nota(name, first_sub, last_sub, new_text):
    starts = [k for k, l in enumerate(lines) if first_sub in l]
    assert len(starts) == 1, '%s: 首行匹配 %d 次' % (name, len(starts))
    i = starts[0]
    ends = [k for k in range(i, len(lines)) if last_sub in lines[k]]
    assert ends, '%s: 末行未找到' % name
    j = ends[0]
    seg = lines[i:j + 1]
    for k, l in enumerate(seg):
        t = l.strip()
        assert t == '' or t.startswith('//'), '%s: 第 %d 行非注释 → %r' % (name, i + k + 1, l)
    body = new_text.split('\n')
    total[0] += len(seg) - len(body)
    lines[i:j + 1] = body
    print('ok %-16s 行 %d-%d (%d行) → %d行' % (name, i + 1, j + 1, len(seg), len(body)))


